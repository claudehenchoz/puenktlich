"""Completeness tracking: official fleet lists (data/reference) vs implemented vehicles."""

from __future__ import annotations

from dataclasses import dataclass

from puenktlich.schema import references, vehicles


@dataclass
class OperatorCoverage:
    operator: str
    source: str
    total: int
    done: list[str]
    missing: list[str]

    @property
    def percent(self) -> float:
        return 100.0 * len(self.done) / self.total if self.total else 0.0


def coverage() -> list[OperatorCoverage]:
    implemented = {r for v in vehicles().values() for r in v.reference}
    out = []
    for ref in references().values():
        scoped = [e for e in ref.entries if e.in_scope]
        done = [e.id for e in scoped if e.id in implemented]
        missing = [e.id for e in scoped if e.id not in implemented]
        out.append(OperatorCoverage(ref.operator, ref.source, len(scoped), done, missing))
    return out


def report_markdown() -> str:
    lines = [
        "# Completeness",
        "",
        "Generated by `pk coverage` — do not edit by hand.",
        "",
        "| Operator | Done | Total | % |",
        "|---|---:|---:|---:|",
    ]
    cov = coverage()
    for c in cov:
        lines.append(f"| {c.operator.upper()} | {len(c.done)} | {c.total} | {c.percent:.1f} |")
    total = sum(c.total for c in cov)
    done = sum(len(c.done) for c in cov)
    lines.append(f"| **All** | **{done}** | **{total}** | **{100 * done / total if total else 0:.1f}** |")
    entries = {e.id: e for r in references().values() for e in r.entries}
    for c in cov:
        lines += ["", f"## {c.operator.upper()}", "", f"Source: {c.source}", ""]
        for eid in c.done + c.missing:
            e = entries[eid]
            mark = "x" if eid in c.done else " "
            built = f" ({e.built})" if e.built else ""
            lines.append(f"- [{mark}] {e.name}{built} — {e.category}, {e.gauge}")
    return "\n".join(lines) + "\n"
