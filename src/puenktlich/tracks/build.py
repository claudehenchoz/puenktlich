"""Build the companion track GRF (build/puenktlich_tracks.grf): metre-gauge railtypes with
procedurally drawn ballast (underlay) and rails (track_overlay). Everything else
(tunnels, bridges, crossings, depots, catenary, signals, GUI) falls back to the base set."""

from __future__ import annotations

import hashlib
import subprocess
from pathlib import Path

import numpy as np
import yaml
from PIL import Image

from puenktlich import paths
from puenktlich.nml.generate import LANG_FILES, LANG_IDS, Strings, project_version
from puenktlich.render import SCALES
from puenktlich.tracks.infra import infra_sprites
from puenktlich.tracks.raster import STYLES, Sprite, quantise, track_sprites
from puenktlich.voxel.palette import rgb_palette

GRFID = "PK\\43\\54"  # "PKCT" — never change after the first public release
OUT = paths.BUILD / "tracks"
SPACING = 8
ZOOMS = {1: "ZOOM_LEVEL_NORMAL", 2: "ZOOM_LEVEL_IN_2X", 4: "ZOOM_LEVEL_IN_4X"}
# 8bpp: never use transparent 0, company colours (80–87, 198–205), animated ranges (217+)
ALLOWED = np.array([i for i in range(1, 217) if not (80 <= i <= 87 or 198 <= i <= 205)])


def _sheet(sprites: list[Sprite]) -> tuple[Image.Image, list[tuple[int, int, int, int, int, int]]]:
    w = sum(s.image.width for s in sprites) + SPACING * len(sprites)
    h = max(s.image.height for s in sprites)
    sheet = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    rects, x = [], 0
    for s in sprites:
        sheet.alpha_composite(s.image, (x, 0))
        rects.append((x, 0, s.image.width, s.image.height, s.xofs, s.yofs))
        x += s.image.width + SPACING
    return sheet, rects


GROUPS = (
    "underlay",
    "track_overlay",
    "level_crossings",
    "bridge_surfaces",
    "tunnels",
    "tunnel_overlay",
    "depots",
    "gui",
)


def write_sheets(styles: set[str], out: Path = OUT) -> dict[str, dict[str, dict[int, tuple[str, str, list]]]]:
    """style -> group -> zoom -> (32bpp path, 8bpp path, rects) for every railtype sprite group."""
    out.mkdir(parents=True, exist_ok=True)
    result: dict[str, dict[str, dict[int, tuple[str, str, list]]]] = {}
    for style_name in sorted(styles):
        style = STYLES[style_name]
        for zoom in SCALES:
            groups = track_sprites(style, zoom) | infra_sprites(style, zoom)
            for group in GROUPS:
                sheet, rects = _sheet(groups[group])
                stem = f"{style_name}_{group}_{zoom}x"
                p32 = out / f"{stem}_32bpp.png"
                sheet.save(p32)
                p8 = ""
                if zoom == 1:
                    p8p = out / f"{stem}_8bpp.png"
                    quantise(sheet, rgb_palette(), ALLOWED).save(p8p)
                    p8 = p8p.relative_to(paths.ROOT).as_posix()
                result.setdefault(style_name, {}).setdefault(group, {})[zoom] = (
                    p32.relative_to(paths.ROOT).as_posix(),
                    p8,
                    rects,
                )
    return result


def _nml(sheets: dict, railtypes: list[dict], strings: Strings) -> str:
    major, minor, patch = (int(x) for x in project_version().split(".")[:3])
    lines = [
        "// Generated by `pk build` — do not edit. Source: data/tracks.yaml, src/puenktlich/tracks/",
        "grf {",
        f'    grfid: "{GRFID}";',
        "    name: string(STR_TRACKS_GRF_NAME);",
        "    desc: string(STR_TRACKS_GRF_DESC);",
        "    url: string(STR_GRF_URL);",
        f"    version: {major * 10000 + minor * 100 + patch};",
        "    min_compatible_version: 0;",
        "}",
        "",
    ]
    labels = sorted({lab for rt in railtypes for lab in [rt["label"], *rt["compatible"], *rt["powered"]]})
    lines += ["railtypetable {", *[f"    {lab}," for lab in labels], "}", ""]
    for style_name, groups in sheets.items():
        for group, zooms in groups.items():
            p32, p8, rects = zooms[1]
            ss = f"ss_{style_name}_{group}"
            lines.append(f'spriteset({ss}, "{p8}") {{')
            lines += [f"    [{x}, {y}, {w}, {h}, {xo}, {yo}]" for x, y, w, h, xo, yo in rects]
            lines.append("}")
            for zoom in SCALES:
                p32, _, rects = zooms[zoom]
                lines.append(f'alternative_sprites({ss}, {ZOOMS[zoom]}, BIT_DEPTH_32BPP, "{p32}") {{')
                lines += [f"    [{x}, {y}, {w}, {h}, {xo}, {yo}]" for x, y, w, h, xo, yo in rects]
                lines.append("}")
            lines.append("")
    for i, rt in enumerate(railtypes):
        lab = rt["label"]
        s_name = strings.add(f"STR_RT_{lab}_NAME", rt["name"])
        s_short = strings.add(f"STR_RT_{lab}_SHORT", rt["short"])
        flags = "bitmask(RAILTYPE_FLAG_CATENARY)" if rt["catenary"] else "bitmask()"
        lists = {k: ", ".join(f'"{x}"' for x in rt[k]) for k in ("compatible", "powered", "alternative")}
        lines += [
            f"item(FEAT_RAILTYPES, rt_{lab.lower()}, {i}) {{",
            "    property {",
            f'        label: "{lab}";',
            f"        name: string({s_name});",
            f"        toolbar_caption: string({s_name});",
            f"        menu_text: string({s_short});",
            f"        build_window_caption: string({s_name});",
            f"        autoreplace_text: string({s_short});",
            f"        new_engine_text: string({s_short});",
            f"        compatible_railtype_list: [{lists['compatible']}];",
            f"        powered_railtype_list: [{lists['powered']}];",
            f"        alternative_railtype_list: [{lists['alternative']}];",
            f"        railtype_flags: {flags};",
            f"        introduction_date: date({rt['intro_year']}, 1, 1);",
            f"        construction_cost: {rt['construction_cost']};",
            f"        maintenance_cost: {rt['maintenance_cost']};",
            f"        speed_limit: {rt.get('speed_limit_kmh', 0)} km/h;"
            if rt.get("speed_limit_kmh")
            else "        speed_limit: 0;",
            "        acceleration_model: ACC_MODEL_RAIL;",
            f"        map_colour: {rt['map_colour']};",
            f"        sort_order: {0x20 + i};",
            "    }",
            "    graphics {",
            *[f"        {g}: ss_{rt['style']}_{g};" for g in GROUPS],
            "    }",
            "}",
            "",
        ]
    return "\n".join(lines)


def _inputs_digest() -> str:
    """Everything the track GRF is generated from (code, data, strings, version, palette)."""
    h = hashlib.sha1()
    files = sorted(Path(__file__).parent.glob("*.py")) + [
        paths.DATA / "tracks.yaml",
        paths.LANG / "strings.yaml",
        paths.ROOT / "pyproject.toml",
        paths.PALETTE_JSON,
    ]
    for f in files:
        h.update(f.name.encode())
        h.update(f.read_bytes())
    return h.hexdigest()


def build_tracks(out_grf: Path | None = None, force: bool = False) -> Path:
    """Build the track GRF; skipped when nothing it depends on changed (digest stamp)."""
    grf = out_grf or paths.BUILD / "puenktlich_tracks.grf"
    stamp = grf.with_suffix(".grf.sha1")
    digest = _inputs_digest()
    if not force and grf.exists() and stamp.exists() and stamp.read_text() == digest:
        return grf
    railtypes = yaml.safe_load((paths.DATA / "tracks.yaml").read_text(encoding="utf-8"))
    strings = Strings()
    static = yaml.safe_load((paths.LANG / "strings.yaml").read_text(encoding="utf-8"))
    for key in ("STR_TRACKS_GRF_NAME", "STR_TRACKS_GRF_DESC", "STR_GRF_URL"):
        strings.add(key, {k: t.replace("{VERSION}", project_version()) for k, t in static[key].items()})
    sheets = write_sheets({rt["style"] for rt in railtypes})
    nml_dir = paths.BUILD / "nml_tracks"
    nml_dir.mkdir(parents=True, exist_ok=True)
    nml = nml_dir / "puenktlich_tracks.nml"
    nml.write_text(_nml(sheets, railtypes, strings), encoding="utf-8")
    strings.write(nml_dir / "lang")
    subprocess.run(
        [
            "nmlc",
            "--quiet",
            "-c",
            "--lang-dir",
            str(nml_dir / "lang"),
            "--cache-dir",
            str(paths.BUILD / ".nmlcache"),
            "--grf",
            str(grf),
            str(nml),
        ],
        cwd=paths.ROOT,
        check=True,
    )
    stamp.write_text(digest)
    return grf


__all__ = ["build_tracks", "write_sheets", "LANG_FILES", "LANG_IDS"]
