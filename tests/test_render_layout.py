import functools
import re

import pytest

from puenktlich import paths
from puenktlich.render import KINDS, PARTS, load_manifest, parts_for, sprite_layout

TW_TEMPLATES = paths.ROOT / ".tools" / "src" / "tw_trains" / "templates" / "static"
TW_NAMES = {
    "normal": "template_auto_{L}_{s}x",
    "turn_1": "template_auto_turn_1_{L}_{s}x",
    "turn_2": "template_auto_turn_2_{L}_{s}x",
    "up": "template_auto_up_{L}_{s}x",
    "down": "template_auto_down_{L}_{s}x",
}


@functools.cache
def _parse_tw() -> dict[str, list[tuple[int, ...]]]:
    out: dict[str, list[tuple[int, ...]]] = {}
    for f in ("sprite_templates.nml", "sprite_templates_hills.nml"):
        text = (TW_TEMPLATES / f).read_text()
        for name, body in re.findall(r"template (\w+)\(\) \{(.*?)\}", text, re.S):
            out[name] = [tuple(int(v) for v in row.split(",")) for row in re.findall(r"\[([^\]]+)\]", body)]
    return out


def _ours(scale: int, length: int, kind: str) -> list[tuple[int, ...]]:
    return [(r.x, r.y, r.w, r.h, r.xrel, r.yrel) for r in sprite_layout(scale, length, kind)]


