@pytest.mark.skipif(not TW_TEMPLATES.exists(), reason="Timberwolf's Trains not cloned into .tools/src/tw_trains")
@pytest.mark.parametrize("length", sorted(PARTS))
@pytest.mark.parametrize("scale", [1, 2])
@pytest.mark.parametrize("kind", KINDS)
def test_layout_matches_timberwolf(kind: str, scale: int, length: int) -> None:
    tw = _parse_tw()
    name = TW_NAMES[kind].format(L=length, s=scale)
    if name not in tw:
        pytest.skip(f"{name} not generated by Timberwolf")
    assert _ours(scale, length, kind) == tw[name]


def test_layout_scales_linearly() -> None:
    for kind in KINDS:
        one, four = sprite_layout(1, 8, kind), sprite_layout(4, 8, kind)
        for a, b in zip(one, four, strict=True):
            if a.w > 1:
                assert (b.x, b.w, b.h) == (a.x * 4, a.w * 4, a.h * 4)


def test_parts_sum_to_length() -> None:
    for length, parts in PARTS.items():
        assert sum(parts) == length
    assert parts_for(2) == (2,)


